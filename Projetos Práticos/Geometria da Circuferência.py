raio = float(input("Informe o valor do Raio da Circuferência: "))
area = 3.14 * (raio ** 2)
diametro = 2 * raio
comprimento = 2 * 3.14 * raio

print("A área da Circuferência é: " + str(round(area,2)))
print("O diâmetro da Circuferência é: " + str(round(diametro,2)))
print("O comprimento da Circuferência é: " + str(round(comprimento,2)))
