#Chamando a biblioteca com funções matemáticas prontas
import math

'''
Ordem dos Operadores
1: Parenteses ()
2: Potência pow(base,potência) / Raíz Quadrada sqrt()
3: * / 
4: + - 
'''
#Exemplo com dois números
n1 = 10
n2 = 2

#Exemplo de Parenteses
ex1 = n1 + n2 + (n1 + n2)

#Exemplo de Potenciação (Potência)
ex2 = pow(10,2)

#Exemplo de Radiciação (Raíz Quadrada)
ex3 = math.sqrt(n1)

print(ex1)
print(ex2)
print(ex3)

